/* ============================================================
   ARC · 支线热点条目模板（数据库）
   ------------------------------------------------------------
   用法：复制本文件到 database/ 下，重命名为 英文id.js
   （例如 db-001.js），然后：
   1. 把下面两处 'db-001' 改成你的条目 id（唯一、英文）
   2. 填写 title / date
   3. 在 content 的反引号内写条目内容（Markdown）
   4. 填写 keywords：自定义模糊搜索关键词，读者搜索时
      会匹配 标题 + 这些关键词
   5. 在 config.js 的 database 数组里注册这个条目，
      并给它一个 publish（发布周期，ARC 日序号）：
      每个周期 = 一批热点（如 3月11日 那批 = ARC 日 001，
      3月16日 那批 = ARC 日 002）；
      只有 发布周期 <= 当前系统时间 的条目才会出现在
      "搜索热点"中、可被搜索到
   ============================================================ */

window.ARC_CONTENT = window.ARC_CONTENT || {};

ARC_CONTENT['db-001'] = {

  /* 条目标题 */
  title: '热点条目示例',

  /* 可选：日期 */
  date: '2026-10-25',

  /* 自定义模糊搜索关键词：确保能被读者搜到 */
  keywords: ['关键词A', '关键词B', '另一个可搜到的词'],

  /* 条目内容（Markdown），支持行间批注 {{@用户名|索引词句|批注内容}} */
  content: `
# 条目标题

热点条目的正文内容，供读者自行检索查阅。

{{@记录员|条目标题|热点条目里也可以写批注，索引词句可点击回到原文。}}
`
};

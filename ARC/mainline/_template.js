/* ============================================================
   ARC · 主线文章模板
   ------------------------------------------------------------
   用法：复制本文件到 mainline/ 下，重命名为 英文id.js
   （例如 log-001.js），然后：
   1. 把下面两处 'log-001' 改成你的文章 id（唯一、英文）
   2. 填写 title / date
   3. 在 content 的 ``` 反引号 内写 Markdown 正文
   4. 在 config.js 的 mainline 数组里注册这篇文章
   ============================================================ */

window.ARC_CONTENT = window.ARC_CONTENT || {};

ARC_CONTENT['log-001'] = {

  /* 自定义标题（目录与页内都显示这个） */
  title: '日志标题示例',

  /* 可选：日期 */
  date: '2026-10-25',

  /* ---------- 正文：Markdown ----------
     支持：标题(#)、粗体(**)、斜体(*)、引用(>)、
     列表(- / 1.)、代码块(```)、分隔线(---)、链接、图片
     行间距由站点统一控制，自动拉大。

     【行间批注】写在正文里（必须锚定被批注的原文词/句）：
       {{@用户名|索引词句|批注内容}}
       带讨论区引用的批注：
       {{@用户名|索引词句|批注内容|讨论条目id}}
       索引词句 = 被批注的原文词汇或句子，会显示在批注块首行，
       点击可跳回原文对应位置并高亮。
     【词条跳转】正文中出现 config.js glossary 里的词时自动可点击。
     ------------------------------------------------ */
  content: `
# 章节标题

这里是正文段落，**支持 Markdown**。行与行之间间距会自动拉大，适合长文阅读。

> 引用块示例：这是摘自某份档案的引文。

{{@记录员|正文段落|这是行间批注，首行会显示被批注的词句"正文段落"，点击可回到原文。}}

普通段落继续……如果批注有多条，行距会自动适配，不会挤在一起。

- 列表项一
- 列表项二

1. 有序列表一
2. 有序列表二

\`\`\`
代码块 / 终端记录示例
\`\`\`
`,

  /* ---------- 讨论区（帖子式，只读展示） ----------
     每条讨论 = 一个楼层，可嵌套 replies 无限层级。
     字段：
       id      讨论条唯一 id（批注里引用它）
       user    用户名
       text    内容
       quote   可选：若该讨论是从某条批注"引用下来"的，
               填那条批注的【索引词句】，讨论条上会标注"引用批注 ·「…」"
       replies 可选：子回复数组，结构相同（可无限嵌套）

     批注里引用讨论条目时，写 {{@用户|索引词句|内容|c1}}，
     读者点击"↳ 讨论"跳到对应楼层；有 quote 的楼层提供"↑ 回原文"。 */
  comments: [
    {
      id: 'c1', user: '记录员', text: '从批注引用下来的讨论条。', quote: '批注索引词句',
      replies: [
        { id: 'c1-1', user: '读者甲', text: '子回复：继续下一级讨论。' }
      ]
    },
    { id: 'c2', user: '读者甲', text: '独立讨论条：不引用批注也可以存在。' }
  ]
};
